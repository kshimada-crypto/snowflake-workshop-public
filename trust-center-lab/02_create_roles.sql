-- 学習用アカウントロールを作成し、アプリケーションロールを付与
-- 自分のTrialアカウントで実行。ロール作成とアプリケーションロール付与。
USE ROLE USERADMIN;
CREATE ROLE IF NOT EXISTS LAB_TRUST_CENTER_VIEWER;
CREATE ROLE IF NOT EXISTS LAB_TRUST_CENTER_ADMIN;
CREATE ROLE IF NOT EXISTS LAB_TRUST_CENTER_USAGE_VIEWER;

USE ROLE ACCOUNTADMIN;
GRANT APPLICATION ROLE SNOWFLAKE.TRUST_CENTER_VIEWER
  TO ROLE LAB_TRUST_CENTER_VIEWER;
GRANT APPLICATION ROLE SNOWFLAKE.TRUST_CENTER_ADMIN
  TO ROLE LAB_TRUST_CENTER_ADMIN;
-- 費用確認専用。Trust Centerの閲覧・管理ロールとは分離する。
GRANT DATABASE ROLE SNOWFLAKE.USAGE_VIEWER
  TO ROLE LAB_TRUST_CENTER_USAGE_VIEWER;

USE ROLE SECURITYADMIN;
GRANT USAGE ON WAREHOUSE SNOWFLAKE_LEARNING_WH
  TO ROLE LAB_TRUST_CENTER_USAGE_VIEWER;
